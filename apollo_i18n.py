LANGUAGES = {"en": "English", "de": "Deutsch", "zh": "简体中文"}
_language = "en"

def set_language(language):
    global _language
    if language not in LANGUAGES:
        raise ValueError("Unsupported interface language")
    _language = language

def t(text, language=None):
    language = language or _language
    values = CATALOG.get(text)
    if values is None:
        for prefix, suffix, template, key in (
            ("Transcription busy. Audio saved; retrying in ", " seconds.", "Transcription busy. Audio saved; retrying in {seconds} seconds.", "seconds"),
        ):
            if text.startswith(prefix) and text.endswith(suffix):
                return t(template, language).format(**{key: text[len(prefix):-len(suffix)]})
        return text
    return values[("en", "de", "zh").index(language)] or text

